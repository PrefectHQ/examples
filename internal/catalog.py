"""Discover examples, validate them against the example contract, and build CATALOG.yaml.

The contract is documented in ``internal/example-contract.md``.

Usage::

    python -m internal.catalog          # regenerate CATALOG.yaml
    python -m internal.catalog --check  # fail if invalid or out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG_NAME = "CATALOG.yaml"

PRODUCTS = ("prefect", "dagster", "fastmcp")
CATALOG_ROOTS = (*PRODUCTS, "stacks", "learn", "demos")
FROZEN_ROOTS = ("demos",)

FOLDER_MANIFEST = "example.yaml"
FOLDER_REQUIRED_FILES = ("pyproject.toml", "uv.lock", "README.md")
RUNNER_FIELDS = ("cmd", "args", "env", "dependencies", "icon", "draft")
SKIP_DIRS = {"__pycache__", ".venv", "node_modules"}
EXACT_PIN = re.compile(r"===?\s*[0-9][0-9A-Za-z.+!-]*")

CATALOG_HEADER = """\
# Generated by `python -m internal.catalog`. Do not edit by hand.
# Change an example's frontmatter or example.yaml, then regenerate.
# See internal/example-contract.md.
"""

Product = Literal["prefect", "dagster", "fastmcp"]


class ExampleMeta(BaseModel):
    """Metadata every example declares, in frontmatter or example.yaml."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(min_length=1)
    description: str = Field(min_length=1)
    owner: str = Field(pattern=r"^@[\w.-]+(/[\w.-]+)?$")
    targets: dict[str, str] = Field(min_length=1)
    product: list[Product] = Field(min_length=1)
    status: Literal["maintained", "frozen"] = "maintained"
    test: Literal["run", "import-only", "skip"] = "run"
    requires_secrets: list[str] = Field(default_factory=list)
    timeout: int = Field(default=600, gt=0)
    tags: list[str] = Field(default_factory=list)

    # Runner fields used by the existing single-file tooling.
    cmd: list[str] | None = None
    args: list[str] | None = None
    env: dict[str, str] | None = None
    dependencies: list[str] | None = None
    icon: str | None = None
    draft: bool | None = None

    @field_validator("product", mode="before")
    @classmethod
    def _product_as_list(cls, value: Any) -> Any:
        return [value] if isinstance(value, str) else value


@dataclass
class Example:
    slug: str
    path: str  # repo-relative, POSIX style
    kind: Literal["file", "folder"]
    meta: ExampleMeta

    def to_catalog(self, last_verified: Any = None) -> dict[str, Any]:
        entry: dict[str, Any] = {
            "slug": self.slug,
            "path": self.path,
            "kind": self.kind,
            "title": self.meta.title,
            "description": self.meta.description,
            "product": list(self.meta.product),
            "status": self.meta.status,
            "test": self.meta.test,
            "owner": self.meta.owner,
            "targets": dict(self.meta.targets),
            "requires_secrets": list(self.meta.requires_secrets),
            "timeout": self.meta.timeout,
            "tags": list(self.meta.tags),
        }
        if last_verified is not None:
            entry["last_verified"] = last_verified
        return entry


@dataclass
class Discovery:
    examples: list[Example] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)


class FrontmatterError(ValueError):
    pass


def read_frontmatter(text: str) -> dict[str, Any] | None:
    """Return the ``# ---`` comment frontmatter of a .py file, or None if it has none."""
    lines = text.splitlines()
    start = 1 if lines and lines[0].startswith("#!") else 0
    if start >= len(lines) or lines[start].strip() != "# ---":
        return None

    body: list[str] = []
    for line in lines[start + 1 :]:
        if line.strip() == "# ---":
            data = yaml.safe_load("\n".join(body)) or {}
            if not isinstance(data, dict):
                raise FrontmatterError("frontmatter must be a YAML mapping")
            return data
        if line.startswith("# "):
            body.append(line[2:])
        elif line.strip() == "#":
            body.append("")
        else:
            raise FrontmatterError(f"frontmatter line is not a '# ' comment: {line!r}")
    raise FrontmatterError("frontmatter is not closed with '# ---'")


def _format_validation_error(exc: ValidationError) -> str:
    parts = []
    for err in exc.errors():
        loc = ".".join(str(p) for p in err["loc"]) or "(root)"
        parts.append(f"{loc}: {err['msg']}")
    return "; ".join(parts)


def _apply_location_rules(
    raw: dict[str, Any], top: str, rel: str, errors: list[str]
) -> dict[str, Any] | None:
    """Fill defaults that depend on where the example lives, and check they agree."""
    data = dict(raw)

    if top in PRODUCTS:
        product = data.setdefault("product", [top])
        products = [product] if isinstance(product, str) else product
        if isinstance(products, list) and top not in products:
            errors.append(
                f"{rel}: product must include '{top}' for examples under {top}/"
            )
            return None

    if top in FROZEN_ROOTS:
        status = data.setdefault("status", "frozen")
        if status != "frozen":
            errors.append(f"{rel}: status must be 'frozen' under {top}/")
            return None
        targets = data.get("targets")
        if isinstance(targets, dict):
            loose = [
                f"{name} {spec!r}"
                for name, spec in targets.items()
                if not (isinstance(spec, str) and EXACT_PIN.fullmatch(spec.strip()))
            ]
            if loose:
                errors.append(
                    f"{rel}: targets must pin exact versions under {top}/, "
                    f"such as '==3.4.11'; got {', '.join(loose)}"
                )
                return None

    return data


def _load_example(
    raw: dict[str, Any], *, top: str, rel: str, kind: str, errors: list[str]
) -> ExampleMeta | None:
    if kind == "folder":
        runner = [k for k in RUNNER_FIELDS if k in raw]
        if runner:
            errors.append(
                f"{rel}: {', '.join(runner)} only apply to single-file examples; "
                "a folder example runs from its own pyproject.toml"
            )
            return None

    data = _apply_location_rules(raw, top, rel, errors)
    if data is None:
        return None
    try:
        return ExampleMeta.model_validate(data)
    except ValidationError as exc:
        errors.append(f"{rel}: {_format_validation_error(exc)}")
        return None


def _rel(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def _walk(directory: Path, *, top: str, root: Path, result: Discovery) -> None:
    for child in sorted(directory.iterdir()):
        if child.name.startswith(".") or child.name in SKIP_DIRS:
            continue
        if child.is_dir():
            if (child / FOLDER_MANIFEST).is_file():
                _load_folder(child, top=top, root=root, result=result)
            else:
                _walk(child, top=top, root=root, result=result)
        elif child.suffix == ".py" and child.name != "__init__.py":
            _load_file(child, top=top, root=root, result=result)


def _load_folder(folder: Path, *, top: str, root: Path, result: Discovery) -> None:
    rel = _rel(folder, root)
    errors = result.errors

    missing = [name for name in FOLDER_REQUIRED_FILES if not (folder / name).is_file()]
    if missing:
        errors.append(f"{rel}: folder example is missing {', '.join(missing)}")

    nested = [
        _rel(p.parent, root)
        for p in folder.rglob(FOLDER_MANIFEST)
        if p.parent != folder and not (SKIP_DIRS & set(p.parts))
    ]
    if nested:
        errors.append(f"{rel}: folder examples can't be nested ({', '.join(nested)})")

    try:
        raw = yaml.safe_load((folder / FOLDER_MANIFEST).read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        errors.append(f"{rel}/{FOLDER_MANIFEST}: invalid YAML: {exc}")
        return
    if not isinstance(raw, dict):
        errors.append(f"{rel}/{FOLDER_MANIFEST}: must be a YAML mapping")
        return

    meta = _load_example(raw, top=top, rel=rel, kind="folder", errors=errors)
    if meta is not None and not missing:
        result.examples.append(Example(folder.name, rel, "folder", meta))


def _load_file(path: Path, *, top: str, root: Path, result: Discovery) -> None:
    rel = _rel(path, root)
    try:
        raw = read_frontmatter(path.read_text(encoding="utf-8"))
    except (FrontmatterError, yaml.YAMLError) as exc:
        result.errors.append(f"{rel}: {exc}")
        return
    if raw is None:
        result.errors.append(
            f"{rel}: no '# ---' frontmatter. Add one, or move helper code "
            "into a folder example"
        )
        return

    meta = _load_example(raw, top=top, rel=rel, kind="file", errors=result.errors)
    if meta is not None:
        result.examples.append(Example(path.stem, rel, "file", meta))


def discover(root: Path = REPO_ROOT) -> Discovery:
    """Find every example under the catalog roots and validate it."""
    result = Discovery()
    for top in CATALOG_ROOTS:
        top_dir = root / top
        if not top_dir.is_dir():
            continue
        if (top_dir / FOLDER_MANIFEST).exists():
            result.errors.append(
                f"{top}/{FOLDER_MANIFEST}: put examples in a subfolder, not at the top level"
            )
        _walk(top_dir, top=top, root=root, result=result)

    seen: dict[str, str] = {}
    for example in result.examples:
        if example.slug in seen:
            result.errors.append(
                f"slug '{example.slug}' is used by both {seen[example.slug]} "
                f"and {example.path}; rename one"
            )
        else:
            seen[example.slug] = example.path

    result.examples.sort(key=lambda e: e.path)
    return result


def _existing_last_verified(catalog_path: Path) -> dict[str, Any]:
    if not catalog_path.is_file():
        return {}
    data = yaml.safe_load(catalog_path.read_text(encoding="utf-8")) or {}
    return {
        entry["slug"]: entry["last_verified"]
        for entry in data.get("examples") or []
        if isinstance(entry, dict) and "slug" in entry and "last_verified" in entry
    }


def render_catalog(examples: list[Example], last_verified: dict[str, Any]) -> str:
    entries = [e.to_catalog(last_verified.get(e.slug)) for e in examples]
    body = yaml.safe_dump(
        {"examples": entries}, sort_keys=False, allow_unicode=True, width=1000
    )
    return CATALOG_HEADER + body


def build(root: Path = REPO_ROOT) -> tuple[str | None, list[str]]:
    """Return (rendered catalog, errors). The catalog is None if there are errors."""
    found = discover(root)
    if found.errors:
        return None, found.errors
    last_verified = _existing_last_verified(root / CATALOG_NAME)
    return render_catalog(found.examples, last_verified), []


def main(argv: list[str] | None = None, root: Path = REPO_ROOT) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m internal.catalog",
        description="Validate examples and build CATALOG.yaml",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Don't write; fail if an example is invalid or CATALOG.yaml is out of date",
    )
    args = parser.parse_args(argv)

    rendered, errors = build(root)
    if errors:
        print(
            f"{len(errors)} example(s) break the contract (internal/example-contract.md):"
        )
        for error in errors:
            print(f"  - {error}")
        return 1

    catalog_path = root / CATALOG_NAME
    current = (
        catalog_path.read_text(encoding="utf-8") if catalog_path.is_file() else None
    )

    if args.check:
        if current != rendered:
            print(
                f"{CATALOG_NAME} is out of date. Run `python -m internal.catalog` and commit it."
            )
            return 1
        print(f"{CATALOG_NAME} is up to date.")
        return 0

    if current != rendered:
        catalog_path.write_text(rendered, encoding="utf-8")
        print(f"Wrote {CATALOG_NAME}.")
    else:
        print(f"{CATALOG_NAME} already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
